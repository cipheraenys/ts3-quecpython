"""Generate ec600m_api_names.h: the kernel export names this image can look up at runtime.

A name is listed when it is a by-name stub in the EC600M ql_common_api (its object holds the
name string) and libHeliosAPI.a or the SDK sources call it, or when the shim forwards it.

usage: gen_api_names.py <sdk root> <ql_common_api.a> <libHeliosAPI.a> <ec600m_shim.c> <out.h>
env:   CROSS (toolchain prefix)
"""
import os
import re
import subprocess
import sys
import tempfile

sdk, api_lib, helios_lib, shim, out = sys.argv[1:6]
CROSS = os.environ.get("CROSS", os.path.expanduser(
    "~/helios_tc/gcc-arm-none-eabi-10-2020-q4-major/bin/arm-none-eabi-"))


def run(*a):
    return subprocess.run(a, capture_output=True, text=True, check=True).stdout


defined = {}  # function -> object
for line in run(CROSS + "nm", "-A", "--defined-only", api_lib).splitlines():
    m = re.match(r".*:(\S+\.o):[0-9a-f]+ T (\w+)$", line)
    if m:
        defined[m.group(2)] = m.group(1)
with tempfile.TemporaryDirectory() as tmp:
    subprocess.run([CROSS + "ar", "x", os.path.abspath(api_lib)], cwd=tmp, check=True)
    strings = {o: set(run("strings", "-a", os.path.join(tmp, o)).split()) for o in set(defined.values())}
stubs = {n for n, o in defined.items() if n in strings[o]}

called = set()
for line in run(CROSS + "nm", "-u", helios_lib).splitlines():
    p = line.split()
    if p and p[-1] in stubs:
        called.add(p[-1])
ident = re.compile(r"\b((?:ql|lwip)_\w+)\s*\(")
for root, dirs, files in os.walk(sdk):
    if "/output" in root or "/.git" in root:
        continue
    for f in files:
        if f.endswith((".c", ".h")):
            for n in ident.findall(open(os.path.join(root, f), errors="replace").read()):
                if n in stubs:
                    called.add(n)

src = open(shim).read()
called |= set(re.findall(r"^FWD\((\w+)\)", src, re.M))
called |= {k for _, k in re.findall(r"^FWD_AS\((\w+),\s*(\w+)\)", src, re.M)}

names = sorted(called)
with open(out, "w") as f:
    f.write("/* generated by gen_api_names.py */\n")
    f.write("static const char *const ec600m_api_names[] = {\n")
    for n in names:
        f.write('    "%s",\n' % n)
    f.write("    0,\n};\n")
print("ec600m_api_names.h: %d names (%d ql_common_api stubs)" % (len(names), len(stubs)))
